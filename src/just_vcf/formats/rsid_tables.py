"""Genotype tables keyed by rsid in the 23andMe layout, and the exports that copy it.

One line per site: identifier, chromosome, position, genotype. An absent site is unknown, never
hom-ref: array exports drop no-calls and cover only the chip's sites.
"""

import polars as pl

from just_vcf.formats.spec import BuildHint, ColumnSpec, Detection, Family, FormatSpec, HeaderMode

RSID_COLUMNS: tuple[ColumnSpec, ...] = (
    {"name": "rsid", "dtype": pl.String, "description": "rsid, or a vendor-internal id such as i713426"},
    {"name": "chromosome", "dtype": pl.String, "description": "1-22, X, Y, MT; no chr prefix"},
    {"name": "position", "dtype": pl.Int64, "description": "1-based position on the stated build"},
    {"name": "genotype", "dtype": pl.String, "description": "two allele letters, or one on haploid sites"},
)

TWENTYTHREE_AND_ME = FormatSpec(
    id="23andme",
    family=Family.GENOTYPE_TABLE,
    vendor="23andMe",
    description="23andMe raw data download, all chip versions (v1 to v5).",
    detection=Detection(
        patterns=(r"^# This data file generated by 23andMe",),
        data_shape=r"(rs|i)\d+\t(\d{1,2}|X|Y|MT)\t\d+\t([ACGTDI]{1,2}|--)",
    ),
    header=HeaderMode.COMMENTED,
    columns=RSID_COLUMNS,
    genotype_encoding=(
        "plus-strand allele letters; one letter on haploid sites (male X/Y, MT); "
        "D/I on indel probes, which the loader resolves against the probe's alleles"
    ),
    no_call=("--",),
    build_hints=(
        BuildHint(r"reference human assembly build 36", "GRCh36"),
        BuildHint(r"reference human assembly build 37", "GRCh37"),
    ),
    notes=("2011 exports are build 36; the header says so, and the loader must not assume 37.",),
    example=(
        "# This data file generated by 23andMe at: Wed Apr 11 08:10:59 2018\n"
        "#\n"
        "# We are using reference human assembly build 37 (also known as Annotation Release 104).\n"
        "#\n"
        "# rsid\tchromosome\tposition\tgenotype\n"
        "rs548049170\t1\t69869\tTT\n"
        "rs13328684\t1\t74792\t--\n"
        "i713426\t1\t726912\tAG\n"
        "rs3094315\t1\t752566\tAA\n"
    ),
)

SPECS: tuple[FormatSpec, ...] = (TWENTYTHREE_AND_ME,)
FALLBACKS: tuple[FormatSpec, ...] = ()
