"""Genotype tables keyed by rsid in the 23andMe layout, and the exports that copy it.

One line per site: identifier, chromosome, position, genotype. An absent site is unknown, never
hom-ref: array exports drop no-calls and cover only the chip's sites.

Order inside `SPECS`: Genes for Good before PLINK, because every Genes for Good export is written by
PLINK and carries PLINK's own preamble line under its vendor line; imputed before unphased Genes for
Good, though their headers are disjoint. `FALLBACKS` hold the tables without a vendor preamble: a bare
commented column line first, then the fully headerless table recognised by data shape alone.
"""

import polars as pl

from just_vcf.formats.spec import (
    BuildHint,
    ColumnSpec,
    Detection,
    Family,
    FormatSpec,
    HeaderMode,
)

_CHROM = r"(\d{1,2}|X|Y|MT)"
"""Chromosome codes seen in these tables: 1-22, X, Y, MT; never a `chr` prefix."""

_TWENTYTHREE_AND_ME_SHAPE = rf"(rs|i)\d+\t{_CHROM}\t\d+\t([ACGTDI]{{1,2}}|--)"
"""A 23andMe data line: rsid or internal `i` id, chromosome, position, one or two letters or `--`."""

_PLINK_SHAPE = rf"\S+\t{_CHROM}\t\d+\t[ACGTDI-]{{1,2}}"
"""A PLINK `--recode 23` data line: any id (imputed sites have none), half-calls such as `T-`."""


def _rsid_columns(id_description: str, genotype_description: str) -> tuple[ColumnSpec, ...]:
    """The four columns of the 23andMe layout, with the identifier and genotype described per export."""
    return (
        {"name": "rsid", "dtype": pl.String, "description": id_description},
        {"name": "chromosome", "dtype": pl.String, "description": "1-22, X, Y, MT; no chr prefix"},
        {"name": "position", "dtype": pl.Int64, "description": "1-based position on the stated build"},
        {"name": "genotype", "dtype": pl.String, "description": genotype_description},
    )


RSID_COLUMNS: tuple[ColumnSpec, ...] = _rsid_columns(
    "rsid, or a vendor-internal id such as i713426",
    "two allele letters, or one on haploid sites",
)

GENES_FOR_GOOD_COLUMNS: tuple[ColumnSpec, ...] = _rsid_columns(
    "rsid; sites without one are `chrom:posREF>ALT` (v1.0 imputed) or `chrom:pos_REF/ALT` (v1.2), "
    "where ALT may be `-` or a symbolic allele such as `<CN0>` or `<INS:ME:ALU>`",
    "two allele letters, one on haploid sites, I/D codes, `-` for a missing allele",
)

