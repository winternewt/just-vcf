GENOS = FormatSpec(
    id="genos",
    family=Family.GENOTYPE_TABLE,
    vendor="Genos",
    description=(
        "Genos exome genotype TSV (`##FileFormat=Genos`) at a request list of sites, including the "
        "file Genos labelled `Promethease_format`, which has the same layout."
    ),
    detection=Detection(
        patterns=(r"\A##FileFormat=Genos\r?$",),
        data_shape=r"chr([1-9]|1\d|2[0-2]|X|Y|M)\t\d+\t\d+\t\S+\t\S+",
    ),
    comment_prefix="#",
    delimiter="\t",
    header=HeaderMode.NONE,
    columns=(
        {"name": "chromosome", "dtype": pl.String, "description": "chr-prefixed: chr1-chr22, chrX, chrY"},
        {"name": "begin", "dtype": pl.Int64, "description": "0-based start of the reference span"},
        {"name": "end", "dtype": pl.Int64, "description": "exclusive end; equals begin at an insertion site"},
        {"name": "rsid", "dtype": pl.String, "description": "rsid of the requested site"},
        {"name": "genotype", "dtype": pl.String, "description": "alleles joined by `/`, or one allele"},
    ),
    coordinates=Coordinates.ZERO_BASED_HALF_OPEN,
    genotype_encoding=(
        "alleles joined by `/`, plus strand in reference orientation; an allele may be several bases "
        "(indels, MNPs); `-` is an empty allele, used at zero-length insertion sites (begin == end); a "
        "single allele with no `/` is a hemizygous call on chrX/chrY"
    ),
    no_call=(),
    build_hints=(BuildHint(r"^##ReferenceGenome=UCSC\.hg19\r?$", "GRCh37"),),
    notes=(
        "Column names are stated in the `##Columns=CHROM\\tBEGIN\\tEND\\tID\\tGENOTYPE` meta line, not in a "
        "header line; `columns` gives them in file order.",
        "`-/-` is NOT a no-call: it is homozygous for the empty allele (no insertion) at a site whose "
        "reference span is empty. No no-call spelling was observed.",
        "BEGIN is 0-based and END exclusive: for an SNV the 1-based position is END (checked against "
        "GRCh37 array positions of the same rsids).",
        "Rows are only the sites on the `##RequestList=` (SNPedia_jan2017 in every file seen), not the "
        "whole exome; the file does not say whether a hom-ref row was actually covered.",
        "`##Sample=` holds a kit number.",
    ),
    example=(
        "##FileFormat=Genos\n"
        "##DataVersion=1.0.0\n"
        "##ReferenceGenome=UCSC.hg19\n"
        "##RequestList=SNPedia_jan2017\n"
        "##Columns=CHROM\tBEGIN\tEND\tID\tGENOTYPE\n"
        "chr1\t935070\t935071\trs139739199\tC/T\n"
        "chr1\t949607\t949608\trs1921\tA/G\n"
        "chr1\t949699\t949699\trs672601345\t-/-\n"
        "chr1\t1147421\t1147422\trs17568\tT/T\n"
    ),
)

