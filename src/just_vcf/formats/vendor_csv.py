        {
            "name": "chromosome",
            "dtype": pl.String,
            "description": "numeric only: 1-22, then 23, 24, 25 and 26 for the non-autosomes",
        },
        {"name": "position", "dtype": pl.Int64, "description": "1-based position on the stated build"},
        {"name": "allele1", "dtype": pl.String, "description": "first observed allele"},
        {"name": "allele2", "dtype": pl.String, "description": "second observed allele"},
