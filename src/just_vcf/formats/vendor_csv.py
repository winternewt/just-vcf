"""Vendor genotype tables that are not 23andMe-shaped.

AncestryDNA, FamilyTreeDNA Family Finder, deCODEme, National Geographic Geno 2.0, Genos and Color.
Each was specified from real PGP-HMS exports (heads only); notes record what those files showed.
Every table here covers predefined sites, so an absent site is unknown, never hom-ref.

Detection leans on the vendor's own header line. Where the files do not name the vendor (the
`RSID,CHROMOSOME,POSITION,RESULT` layout), `ftdna` claims only the shapes FamilyTreeDNA exports were
seen to have, and everything else with that header falls to the vendor-neutral `rsid_result_csv`.
"""

import polars as pl

from just_vcf.formats.spec import (
    BuildHint,
    ColumnSpec,
    Coordinates,
    Detection,
    Family,
    FormatSpec,
    HeaderMode,
)

_AUTOSOME_OR_SEX = r"([1-9]|1\d|2[0-2]|X|Y|MT)"
"""FTDNA chromosome spellings seen in data rows. Excludes `0`, which a GSA export uses for unplaced
probes and which FTDNA exports did not show."""

