CENSUS_EXPECTATIONS: tuple[tuple[str, frozenset[str]], ...] = (
    (r"Genes for Good v[\d.]+: filtered, imputed", frozenset({"genes_for_good_imputed"})),
    (r"Genes for Good v[\d.]+: filtered, unph", frozenset({"genes_for_good"})),
    # The census cuts signatures at 40 characters, which can fall before "imputed"/"unphased".
    (r"Genes for Good v[\d.]+: ", frozenset({"genes_for_good", "genes_for_good_imputed"})),
    (r"^hash:23andMe$", frozenset({"23andme", "23andme_csv", "rsid_table"})),
    (r"^hash:Living DNA", frozenset({"living_dna"})),
    (r"^hash:# Pipeline Version", frozenset({"selfdecode"})),
    (r"^hash:# This data file generated by PLINK", frozenset({"plink_23"})),
    (r"^hash:#Promethease\\ttab-genotype", frozenset({"promethease_tab_genotype"})),
    (r"^hash:# rsid\\tchromosome\\tposition\\tgenotype", frozenset({"rsid_table"})),
    (r"^text:rs\d+\\t", frozenset({"rsid_table_headerless"})),
)
"""Census first-line signature (as the census escapes it) -> the ids such a file may detect as."""



def _census_rows(root: Path) -> list[tuple[Path, str, str]]:
    if not (root / "catalog" / "content_census.tsv").is_file():
        pytest.skip(f"no PGP-HMS content census under {root}")
    rows = []
    for line in (root / "catalog" / "content_census.tsv").read_text().splitlines():
        rel, layer, signature = line.split("\t", 2)
        path = root / "participants" / rel
        if rel.endswith(".part") or not path.is_file():
            continue
        rows.append((path, layer, signature))
    return rows


def _head(path: Path, layer: str, size: int = 4096) -> bytes:
    """The first bytes of a raw, gzip, bz2 or single-member zip file."""
    if layer.startswith("zip"):
        with zipfile.ZipFile(path) as zf:
            largest = max(zf.infolist(), key=lambda info: info.file_size)
            with zf.open(largest) as handle:
                return handle.read(size)
    opener = {"gz": gzip.open, "bz2": bz2.open}.get(layer.split(":")[0], open)
    with opener(path, "rb") as handle:
        return handle.read(size)


def test_real_census_files_detect_as_the_family_their_first_line_names(pgp_root: Path) -> None:
    root = pgp_root
    checked = 0
    wrong: list[str] = []
    for path, _, signature in _census_rows(root):
        expected = next((ids for regex, ids in CENSUS_EXPECTATIONS if re.search(regex, signature)), None)
        if expected is None:
            continue
        result = sniff(path)
        checked += 1
        if result.format not in expected:
            wrong.append(f"{path.relative_to(root)}: {signature[:40]!r} -> {result.format or result.outcome.value}")
    if not checked:
        pytest.skip("no census file of this family is on disk")
    assert not wrong, "\n".join(wrong)


def test_real_gfg_build_is_grch37_exactly_when_the_header_names_it(pgp_root: Path) -> None:
    root = pgp_root
    checked = 0
    for path, layer, signature in _census_rows(root):
        if "Genes for Good v" not in signature:
            continue
        states = b"Human genome reference used: GRCh37" in _head(path, layer)
        assert sniff(path).build == ("GRCh37" if states else None), path.relative_to(root)
        checked += 1
    if not checked:
        pytest.skip("no Genes for Good file is on disk")


def test_real_files_named_like_gfg_or_living_dna_detect_as_those_vendors(pgp_root: Path) -> None:
    """A name-based view of the same files, from a glob rather than the census."""
    root = pgp_root
    families = {
        re.compile(r"gfg.*23andme", re.IGNORECASE): {"genes_for_good", "genes_for_good_imputed"},
        re.compile(r"^living-dna", re.IGNORECASE): {"living_dna"},
        re.compile(r"^selfdecode", re.IGNORECASE): {"selfdecode"},
    }
    checked = 0
    for path in sorted((root / "participants").glob("*/upload-*/*")):
        if path.suffix == ".part" or not path.is_file():
            continue
        expected = next((ids for regex, ids in families.items() if regex.search(path.name)), None)
        if expected is None:
            continue
        assert sniff(path).format in expected, path.relative_to(root)
        checked += 1
    if not checked:
        pytest.skip("no file named like these vendors is on disk")


def test_real_family_detections_come_only_from_family_files(pgp_root: Path) -> None:
    """Precision: nothing outside the family's census signatures detects as one of its ids.

    A multi-member archive is judged by its detected member, which the census signature (taken from
    the largest member) may not describe; those are left out.
    """
    root = pgp_root
    family_signature = re.compile("|".join(regex for regex, _ in CENSUS_EXPECTATIONS))
    captured: list[str] = []
    for path, _, signature in _census_rows(root):
        if family_signature.search(signature):
            continue
        result = sniff(path)
        if result.format in FAMILY_IDS and not result.members:
            captured.append(f"{path.relative_to(root)}: {signature[:40]!r} -> {result.format}")
    assert not captured, "\n".join(captured)
