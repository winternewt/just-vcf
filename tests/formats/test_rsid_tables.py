def _sniff_text(tmp_path: Path, text: str, name: str = "head.txt") -> Sniffed:
    path = tmp_path / name
    path.write_bytes(text.encode("utf-8"))
    return sniff(path)


# --- every spec detects as itself -----------------------------------------------------------------


@pytest.mark.parametrize("spec", FAMILY_SPECS, ids=lambda s: s.id)
def test_example_detects_as_itself_with_the_family_it_declares(spec: FormatSpec, tmp_path: Path) -> None:
    result = _sniff_text(tmp_path, spec.example)
    assert result.outcome is SniffOutcome.DETECTED, result.reason
    assert (result.format, result.family) == (spec.id, spec.family)


@pytest.mark.parametrize("spec", FAMILY_SPECS, ids=lambda s: s.id)
def test_example_detects_the_same_with_crlf_line_endings(spec: FormatSpec, tmp_path: Path) -> None:
    """Most real exports in this family are CRLF; a pattern anchored with a bare `$` would miss them."""
    result = _sniff_text(tmp_path, spec.example.replace("\n", "\r\n"))
    assert result.format == spec.id


@pytest.mark.parametrize("spec", FAMILY_SPECS, ids=lambda s: s.id)
def test_example_build_is_exactly_what_its_hints_say(spec: FormatSpec, tmp_path: Path) -> None:
    """The build comes from a hint that matches the example's text, and is None when none does."""
    stated = {hint.build for hint in spec.build_hints if re.search(hint.pattern, spec.example, re.MULTILINE)}
    result = _sniff_text(tmp_path, spec.example)
    assert result.build == (stated.pop() if len(stated) == 1 else None)


def test_family_fallbacks_are_registered_after_the_family_signatures() -> None:
    position = {spec.id: index for index, spec in enumerate(REGISTRY)}
    assert max(position[s.id] for s in rsid_tables.SPECS) < min(position[f.id] for f in rsid_tables.FALLBACKS)
    assert [position[f.id] for f in rsid_tables.FALLBACKS] == sorted(position[f.id] for f in rsid_tables.FALLBACKS)


